open Drcpcheck_core.Checker.ProofFacts
open Drcpcheck_core.Checker
open Angstrom
open Big_int_Z

let bufsz = ref (1024 * 1024)

type atom_definition = { id : int; atomic : coq_BoundAtomic }

type inference = {
  constraint_id : big_int;
  premises : int list;
  consequent : int option;
  generated_by : big_int list;
  label : string;
}

type deduction = {
  constraint_id : big_int;
  premises : int list;
  sequence : big_int list;
}

type step =
  | Inference of inference
  | Deduction of deduction
  | AtomDefinition of atom_definition

(* Tail-recursive version of [many] *)
let many_rev p =
  let rec go p acc = (p >>= fun x -> go p (x :: acc)) <|> return acc in
  go p []

let many_tr p = many_rev p >>| List.rev

let ws =
  skip_while (function ' ' | '\t' -> true | _ -> false) <?> "whitespace"

let ws_with_new_line =
  skip_while (function ' ' | '\t' -> true | '\n' -> true | _ -> false)
  <?> "whitespace separator with newline"

let ws_sep =
  take_while1 (function ' ' | '\t' -> true | _ -> false)
  <?> "expected whitespace seperator"

let eol = ws *> char '\n' <* ws_with_new_line <?> "expected newline"

(* Parses Ocaml integers *)
let is_digit = function '0' .. '9' -> true | _ -> false
let is_non_zero_digit = function '1' .. '9' -> true | _ -> false

let assrt p =
  peek_char >>= (function Some c when p c -> return () | _ -> fail "!")

let num first_ok =
  let negb =
    peek_char >>= function
    | Some '-' -> advance 1 *> return true
    | Some '+' -> advance 1 *> return false
    | Some c when first_ok c -> return false
    | _ -> fail "Sign or non-zero digit expected" in
  lift2 (fun negb digits -> (negb, digits)) negb (take_while1 is_digit)

let atomic_code =
  num is_non_zero_digit >>= fun (negb, digits) ->
  let i = int_of_string digits in
  return (if negb then -i else i)
  <?> "expected atomic/constraint id"

(* Parser for a variable name. *)
let is_letter c = (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z')

let ident =
  assrt (fun c -> is_letter c || c = '_') >>= fun () ->
  take_while (fun c -> is_letter c || is_digit c || c = '_') >>= fun rest ->
  return rest <?> "expected variable identifier"

(* Parser for big-integers. *)
let big_integer =
  num is_digit >>= fun (negb, digits) ->
  let bi = big_int_of_string digits in
  return (if negb then Big_int_Z.sub_big_int Big_int_Z.zero_big_int bi else bi)
  <?> "expected big integer"

let cmp =
  choice
    [
      string ">=" *> return Coq_greater_equal <?> "greater equal";
      string "<=" *> return Coq_less_equal <?> "less equal";
      string "==" *> return Coq_equal <?> "equal";
      string "!=" *> return Coq_not_equal <?> "not equal";
    ]
  <?> "expected comparator"

let atom =
  char '['
  *> lift3
       (fun var_name comparator value ->
         (var_name, { atm_cmp = comparator; atm_val = value }))
       ident
       (ws_sep *> cmp <* ws_sep)
       big_integer
  <* char ']' <?> "expected atomic"

let atom_definition =
  char 'a' *> ws_sep
  *> lift2
       (fun atom_id atomic -> { id = atom_id; atomic })
       atomic_code (ws_sep *> atom)
  <* eol <?> "expected atomic definition line"

let inference_rule =
  ident

let premises = many_tr (atomic_code <* ws_sep) <* char '0'

let inference_args =
  let generated_by =
    option [] (ws_sep *> string "c:" *> big_integer >>| fun id -> [ id ])
    <?> "generated by"
  in
  let label = ws_sep *> string "l:" *> inference_rule <?> "inference label" in
  lift2 (fun gb lbl -> (gb, lbl)) generated_by label
  <|> lift2 (fun lbl gb -> (gb, lbl)) label generated_by

let inference_line =
  char 'i' *> ws_sep *> (big_integer <* ws_sep) >>= fun constraint_id ->
  premises >>= fun premises ->
  option None (ws_sep *> atomic_code >>| fun id -> Some id)
  >>= fun consequent ->
  inference_args >>= fun (generated_by, label) ->
  return { constraint_id; premises; consequent; generated_by; label }
  <* eol <?> "inference line"

let deduction_line =
  char 'n' *> ws_sep
  *> lift3
       (fun id premises sequence -> { constraint_id = id; premises; sequence })
       (big_integer <* ws_sep) premises
       (many_tr (ws_sep *> big_integer))
  <* eol <?> "deduction line"

let proof_line =
  ws_with_new_line *> peek_char_fail >>= function
  | 'a' -> atom_definition >>| fun def -> AtomDefinition def
  | 'i' -> inference_line >>| fun inf -> Inference inf
  | 'n' -> deduction_line >>| fun deduction -> Deduction deduction
  | _ -> fail "Unknown proof line"

type conclusion = Unsat | DualBound of int

let conclusion_line =
  char 'c' *> ws_sep
  *> (string "UNSAT" *> return Unsat
     <?> "unsat conclusion"
     <|> (atomic_code
         >>| (fun code -> DualBound code)
         <?> "dual bound conclusion"))
  <* ws_with_new_line <?> "conclusion line"

let proof =
  many_tr proof_line >>= fun steps ->
  conclusion_line >>= fun conclusion -> return (steps, conclusion)

let proof_stage_line =
  ws_with_new_line *> peek_char_fail >>= function
  | 'a' -> atom_definition >>| fun def -> AtomDefinition def
  | 'i' -> inference_line >>| fun inf -> Inference inf
  | _ -> fail "Unknown proof line"

let proof_stage =
  many_rev proof_stage_line >>= fun rev_steps ->
  peek_char >>= function
  | Some 'n' ->
      deduction_line >>| fun d -> (None, List.rev (Deduction d :: rev_steps))
  | Some 'c' -> conclusion_line >>| fun c -> (Some c, List.rev rev_steps)
  | None -> return (None, List.rev rev_steps)
  | Some chr -> fail (Printf.sprintf "Unknown proof line with char [%c]" chr)

exception UndefinedAtomic of int

let negate_atomic = function
  | name, atomic -> (
      match atomic.atm_cmp with
      | Coq_less_equal ->
          ( name,
            {
              atm_cmp = Coq_greater_equal;
              atm_val = succ_big_int atomic.atm_val;
            } )
      | Coq_greater_equal ->
          ( name,
            { atm_cmp = Coq_less_equal; atm_val = pred_big_int atomic.atm_val }
          )
      | Coq_equal ->
          (name, { atm_cmp = Coq_not_equal; atm_val = atomic.atm_val })
      | Coq_not_equal ->
          (name, { atm_cmp = Coq_equal; atm_val = atomic.atm_val }))

let map_tr f l = List.rev (List.rev_map f l)

let dummy_atomic : coq_BoundAtomic =
  ("", { atm_cmp = Coq_equal; atm_val = big_int_of_int 0 })

module Atoms = struct
  type t = {
    mutable pos : coq_BoundAtomic array;
    mutable neg : coq_BoundAtomic array;
    mutable cap : int;
  }

  let create () =
    {
      pos = Array.make 256 dummy_atomic;
      neg = Array.make 256 dummy_atomic;
      cap = 256;
    }

  let ensure t id =
    if id >= t.cap then begin
      let n = Stdlib.max (id + 1) (t.cap * 2) in
      let grow a =
        let b = Array.make n dummy_atomic in
        Array.blit a 0 b 0 t.cap;
        b
      in
      t.pos <- grow t.pos;
      t.neg <- grow t.neg;
      t.cap <- n
    end

  let define t id atom =
    if id <= 0 then raise (UndefinedAtomic id);
    ensure t id;
    t.pos.(id) <- atom;
    t.neg.(id) <- negate_atomic atom

  let resolve t code =
    let i = abs code in
    if i >= t.cap then raise (UndefinedAtomic code);
    let atom = Array.unsafe_get (if code > 0 then t.pos else t.neg) i in
    if atom == dummy_atomic then raise (UndefinedAtomic code);
    atom
end

let convert_inference (atomics : Atoms.t) (inference : inference) :
    indexedInference =
  {
    iinf_index = inference.constraint_id;
    iinf_fact =
      {
        i_premises = map_tr (Atoms.resolve atomics) inference.premises;
        i_consequent = Option.map (Atoms.resolve atomics) inference.consequent;
      };
    iinf_hint = inference.generated_by;
    iinf_rule = inference.label;
  }

exception IncompleteProofError

let rec convert_proof_stage (steps : step list) (atomics : Atoms.t)
    (acc : indexedInference list) : proofStage option * step list =
  match steps with
  | [] -> (None, [])
  | AtomDefinition def :: tail ->
      Atoms.define atomics def.id def.atomic;
      convert_proof_stage tail atomics acc
  | Inference inf :: tail ->
      convert_proof_stage tail atomics (convert_inference atomics inf :: acc)
  | Deduction deduction :: tail ->
      ( Some
          {
            s_inferences = List.rev acc;
            s_conclusion =
              {
                i_premises = map_tr (Atoms.resolve atomics) deduction.premises;
                i_consequent = None;
              };
            s_chain = deduction.sequence;
            s_conclusion_index = deduction.constraint_id;
          },
        tail )

let rec convert_steps_to_proof (steps : step list) (atomics : Atoms.t)
    (acc : proofStage list) : proofStage list =
  match steps with
  | [] -> List.rev acc
  | head :: tail -> (
      match convert_proof_stage (head :: tail) atomics [] with
      | Some stage, rest -> convert_steps_to_proof rest atomics (stage :: acc)
      | None, [] -> List.rev acc
      | None, _ -> raise IncompleteProofError)

exception ParseError of string

let conclusion_fact conclusion atomics =
  match conclusion with
  | Unsat -> { i_premises = []; i_consequent = None }
  | DualBound code ->
      { i_premises = [ Atoms.resolve atomics (-code) ]; i_consequent = None }

type 'st stream_step = Stage of proofStage * 'st | Conclusion of coq_ProofFact

let rec stream_of (step : 'st -> 'st stream_step) (state : 'st) : proofStream =
  match step state with
  | Conclusion conc -> Conclusion conc
  | Stage (stage, state) -> Cons (stage, Thunk (fun () -> stream_of step state))

let stream_stages (consume_one : 'buf -> (conclusion option * step list) * 'buf)
    (buf : 'buf) (atomics : Atoms.t) : proofStream =
  let rec step buf =
    let res, buf = consume_one buf in
    match res with
    | Some conc, steps ->
        (* process any atoms between the last nogood and the conclusion *)
        ignore (convert_proof_stage steps atomics []);
        Conclusion (conclusion_fact conc atomics)
    | None, [] -> raise (ParseError "truncated proof")
    | None, steps -> (
        match convert_proof_stage steps atomics [] with
        | Some stage, _ -> Stage (stage, buf)
        | None, _ -> step buf)
  in
  stream_of step buf

let read_streamed_text in_chan : proofStream =
  let staging = Bytes.create !bufsz in
  let consume w =
    match Parse_window.parse_one in_chan staging proof_stage w with
    | Ok res, w -> (res, w)
    | Error msg, _ -> raise (ParseError msg)
  in
  stream_stages consume
    (Parse_window.create !bufsz)
    (Atoms.create ())

let parse_proof (source : string) : proofStage list * coq_ProofFact =
  match parse_string ~consume:All proof source with
  | Ok (steps, conclusion) ->
      let atomics = Atoms.create () in
      let proof = convert_steps_to_proof steps atomics [] in
      (proof, conclusion_fact conclusion atomics)
  | Error e -> raise (ParseError e)
